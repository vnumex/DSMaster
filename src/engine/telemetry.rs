use crate::emu::EmulationMode;
use crate::protocol::input::TouchPoint;
use crate::protocol::{BatteryStatus, DPad, DualSenseButtons, Transport};

#[derive(Debug, Clone, Copy)]
pub struct TelemetrySnapshot {
    pub active: bool,
    pub is_edge: bool,
    pub transport: Transport,
    pub emulation: EmulationMode,
    pub raw_left_stick: [u8; 2],
    pub raw_right_stick: [u8; 2],
    pub left_stick: [u8; 2],
    pub right_stick: [u8; 2],
    pub l2_analog: u8,
    pub r2_analog: u8,
    pub dpad: DPad,
    pub buttons: DualSenseButtons,
    pub battery_percent: u8,
    pub battery_status: BatteryStatus,
    pub polling_hz: f32,
    pub rumble_large: u8,
    pub rumble_small: u8,
    pub touch: [TouchPoint; 2],
    pub active_lightbar_rgb: Option<[u8; 3]>,
    pub product_id: u16,
    pub mac_address: [u8; 6],
    pub firmware_version: u32,
    pub hardware_version: u32,
    pub firmware_date: [u8; 20],
    pub connected_secs: u32,
    pub idle_secs: u32,
    pub headphone_connected: bool,
    pub mic_connected: bool,
    pub mic_muted_hw: bool,
    pub gyro_dps: [f32; 3],
    pub accel_g: [f32; 3],
    pub bt_audio_streaming: bool,
    pub bt_haptics_streaming: bool,
    pub bt_speaker_level: u8,
    pub bt_haptics_level: u8,
    #[allow(dead_code)]
    pub bt_mic_streaming: bool,
    pub bt_mic_level: u8,
    #[allow(dead_code)]
    pub virtual_audio_attached: bool,
    #[allow(dead_code)]
    pub virtual_speaker_active: bool,
    #[allow(dead_code)]
    pub virtual_mic_active: bool,
}

impl Default for TelemetrySnapshot {
    fn default() -> Self {
        Self {
            active: false,
            is_edge: false,
            transport: Transport::Usb,
            emulation: EmulationMode::None,
            raw_left_stick: [128, 128],
            raw_right_stick: [128, 128],
            left_stick: [128, 128],
            right_stick: [128, 128],
            l2_analog: 0,
            r2_analog: 0,
            dpad: DPad::Center,
            buttons: DualSenseButtons::empty(),
            battery_percent: 0,
            battery_status: BatteryStatus::Unknown,
            polling_hz: 0.0,
            rumble_large: 0,
            rumble_small: 0,
            touch: [TouchPoint::default(); 2],
            active_lightbar_rgb: None,
            product_id: 0,
            mac_address: [0; 6],
            firmware_version: 0,
            hardware_version: 0,
            firmware_date: [0; 20],
            connected_secs: 0,
            idle_secs: 0,
            headphone_connected: false,
            mic_connected: false,
            mic_muted_hw: false,
            gyro_dps: [0.0; 3],
            accel_g: [0.0; 3],
            bt_audio_streaming: false,
            bt_haptics_streaming: false,
            bt_speaker_level: 0,
            bt_haptics_level: 0,
            bt_mic_streaming: false,
            bt_mic_level: 0,
            virtual_audio_attached: false,
            virtual_speaker_active: false,
            virtual_mic_active: false,
        }
    }
}
